"""Pydantic schemas for candidate-job matching scores, breakdown, and reasoning."""

from datetime import datetime, timezone
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class ScoreBreakdown(BaseModel):
    """Detailed deterministic score computation components."""

    coverage_score: float  # Required skill coverage percentage (0-100)
    semantic_score: float  # Top-3 calibrated semantic similarity percentage (0-100)
    preference_score: float  # Preference alignment percentage (0-100)
    raw_similarity: float  # Average uncalibrated cosine similarity
    calibrated_similarity: float  # Average calibrated cosine similarity
    weights_used: Dict[str, float]  # Effective weights applied
    query_text_source: str  # Source of text embedded for semantic query
    preference_penalties: List[Dict[str, Any]] = Field(default_factory=list)
    score_before_caps: int = Field(default=0, ge=0, le=100)
    score_after_caps: int = Field(default=0, ge=0, le=100)
    cap_reasons: List[str] = Field(default_factory=list)


class Match(BaseModel):
    """Candidate-job evaluation result."""

    job_id: str
    score: int = Field(ge=0, le=100, description="Deterministic overall match score from 0 to 100")
    matched_skills: List[str] = Field(default_factory=list)
    missing_skills: List[str] = Field(default_factory=list)
    reasoning: str  # 2-4 sentences generated by LLM (or fallback template)
    preference_conflicts: List[str] = Field(default_factory=list)
    score_breakdown: Dict[str, Any] = Field(default_factory=dict)
    profile_hash: str
    preferences_hash: str
    reasoning_fallback: bool = False
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

